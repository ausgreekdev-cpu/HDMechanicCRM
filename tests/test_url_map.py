def test_url_map_snapshot(app):
    actual = sorted(
        (str(r), sorted(r.methods), r.endpoint)
        for r in app.url_map.iter_rules()
    )
    if os.environ.get("UPDATE_URL_SNAPSHOT") == "1":
        with open(__file__) as f:
            src = f.read()
        start = src.index("EXPECTED_ROUTES = [")
        end = src.index("\n]\n\n\ndef test_url_map_snapshot", start)
        rendered = "EXPECTED_ROUTES = [\n" + "".join(
            f"    ({rule!r}, {methods!r}, {endpoint!r}),\n"
            for rule, methods, endpoint in actual
        ) + "]"
        with open(__file__, "w") as f:
            f.write(src[:start] + rendered + src[end + 2:])
        return
    expected = sorted((rule, methods, endpoint) for rule, methods, endpoint in EXPECTED_ROUTES)
    missing = [e for e in expected if e not in actual]
    added = [a for a in actual if a not in expected]
    assert not missing and not added, f"missing={missing} added={added}"
